import Foundation

enum ProgressiveAnswerPrompt {
    static let version = "progressive-answer-v3"

    /// Product contract: keep this text verbatim. Tests intentionally assert
    /// complete containment so future prompt refactors cannot dilute it.
    static let coreContract = """
    你生成的不是“提纲”和“完整答案”两套内容，
    而是同一份答案的逐层表示。

    在输出任何用户可见字段前，先静默确定：
    1. 面试官真正考察的核心问题；
    2. 一个明确的回答立场；
    3. 2–4 步有顺序、无重复的逻辑主线；
    4. 最多一个主案例及必要证据；
    5. 最能体现本题专业能力的机制、判断标准、行动、
       指标、权衡、失败边界或复盘。
    不要输出上述内部规划。

    entry：
    - 第一分句直接回答核心问题；
    - 第二分句给出关键判断依据、路径或必要假设；
    - 单独阅读时也必须知道候选人的核心判断；
    - 禁止“我会从几个方面回答”“这个问题很重要”等空开场。

    spine：
    - 生成 2–4 个按口述顺序排列的短标题；
    - label 只写标题，不写解释句或详细内容；
    - 锚点之间必须形成因果、决策、时间或论证关系；
    - 禁止“分析问题、制定方案、推动落地”等空泛短语。

    segments：
    - 逐一扩展对应 spine，不得改变 entry 的立场；
    - 必须严格按 spine 的 ID 顺序输出；
    - 每段 1–2 个可直接说出口的句子；
    - 不得新增另一个主案例或新的一级方向；
    - 同一项目含多条独立产品线时，先判断问题具体匹配哪一条，只讲该条线的场景、方案、指标和结果；
    - 不得把另一条产品线当作补充亮点带入，也不得跨线挪用架构、指标或成果；
    - 只有面试官明确询问项目全貌、产品组合或多条线对比时，才可并列概述，并清楚标明各自边界；
    - 专业术语只有在解释机制、决策或验证时才使用；
    - 候选人过去经历和结果必须有 resume/story-bank 引用；
    - 无个人证据时使用专业判断或明确假设式表达。

    closing：
    - 给出成功条件、适用边界、结果或复盘；
    - 不机械重复 entry。

    可见内容顺序：
    - 必须先完整输出 entry；
    - 再完整输出全部 spine 标题；
    - 全部标题完成前不得开始任何 segment；
    - 最后按 spine 顺序逐段输出 segments，再输出 closing。
    """

    static let questionTypeRules = """
    题型规则：
    - 行为题：情境与约束 → 关键判断和行动 → 结果与复盘。
    - 项目深挖：目标与本人职责 → 决策及权衡 → 结果、验证、学习。
    - 产品/业务题：目标与口径 → 诊断和优先级 → 方案、实验、风险。
    - 技术题：结论或定义 → 工作机制 → 选型权衡、失败边界、验证。
    - 动机/自我介绍：定位 → 相关证据 → 岗位贡献。
    - 追问：直接回答 → 最相关证据 → 边界或修正。

    每份回答至少包含两类有效专业信号：机制、判断标准、具体动作、指标验证、权衡边界、失败模式、Ownership 或复盘。
    STAR 等框架只作为内部覆盖规则，不要把框架名、步骤名或制作提示直接输出给用户。
    """

    static func depthRule(_ depth: InterviewAnswerDepth) -> String {
        switch depth {
        case .concise:
            return "回答深度为简短：目标 20–40 秒，通常 2 个锚点；优先保留结论、关键依据和一个验证或边界。"
        case .standard:
            return "回答深度为标准：按题型目标约 30–75 秒，通常 3 个锚点；保持信息完整但可直接口述。"
        case .deep:
            return "回答深度为深入：复杂案例或技术题目标 60–90 秒，生成 3–4 个锚点；补充机制、权衡、失败边界和验证。"
        }
    }
}
